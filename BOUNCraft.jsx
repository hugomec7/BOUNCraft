    // How an expression reads one of its property's controls (see setControls).
    function ctl(name) {
        return "effect(" + JSON.stringify(name) + ")(1)";
    }

    // Second line of an expression that carries its own values instead of reading controls.
    var INLINE = "// Change the values here:";

    // `names`: the controls to read, by value key (from setControls). `inline`: the values to
    // write into the expression itself instead.
    function overshootExpression(axis, names, inline) {
        var head = inline ? [
            TAG + "Overshoot",
            INLINE,
            "var amplitude = " + inline.amp + ";",
            "var frequency = " + inline.freq + ";",
            "var decay = " + inline.decay + ";",
            "var floorOn = " + (inline.floor ? 1 : 0) + ";  // 1: swings to one side only",
            "var on = 1;  // 0: off",
            "// ----------",
            "var amp = amplitude / 1000;",
            "var freq = frequency;",
            "floorOn = floorOn == 1;",
            "on = on == 1;"
        ] : [
            TAG + "Overshoot",
            "var amp = " + ctl(names.amp) + " / 1000;",
            "var freq = " + ctl(names.freq) + ";",
            "var decay = " + ctl(names.decay) + ";",
            names.floor ? "var floorOn = " + ctl(names.floor) + " == 1;" : "var floorOn = false;",
            "var on = true;"
        ];
        return head.concat([
            "var axis = " + axis + ";"
        ], AXIS_LINES, [
            "var out = value;",
            "var n = 0;",
            "if (on && numKeys > 0) {",
            "    n = nearestKey(time).index;",
            "    if (key(n).time > time) n--;",
            "}",
            "if (n > 0) {",
            "    var t = time - key(n).time;",
            "    var v = velocityAtTime(key(n).time - thisComp.frameDuration / 10);",
            "    var wave = Math.sin(freq * t * 2 * Math.PI);",
            "    if (floorOn) wave = -Math.abs(wave);",
            "    out = add(value, only(mul(v, amp * wave / Math.exp(decay * t))));",
            "}",
            "out;"
        ]).join("\n");
    }

    function bounceExpression(axis, names, inline) {
        var head = inline ? [
            TAG + "Bounce Back",
            INLINE,
            "var elasticity = " + inline.elast + ";",
            "var gravity = " + inline.grav + ";",
            "var maxBounces = " + inline.max + ";",
            "var on = 1;  // 0: off",
            "// ----------",
            "elasticity = elasticity / 100;",
            "gravity = gravity * 100;",
            "on = on == 1;"
        ] : [
            TAG + "Bounce Back",
            "var elasticity = " + ctl(names.elast) + " / 100;",
            "var gravity = " + ctl(names.grav) + " * 100;",
            "var maxBounces = " + ctl(names.max) + ";",
            "var on = true;"
        ];
        return head.concat([
            "var axis = " + axis + ";"
        ], AXIS_LINES, [
            "var out = value;",
            "var n = 0;",
            "if (on && numKeys > 0) {",
            "    n = nearestKey(time).index;",
            "    if (key(n).time > time) n--;",
            "}",
            "if (n > 0 && gravity > 0) {",
            "    var t = time - key(n).time;",
            "    var v = mul(velocityAtTime(key(n).time - 0.001), -elasticity);",
            "    var speed = length(v);",
            "    var dir;",
            "    if (typeof value == \"number\") dir = v < 0 ? -1 : 1;",
            "    else dir = speed > 0 ? normalize(v) : mul(v, 0);",
            "    var start = 0;",
            "    var hop = 2 * speed / gravity;",
            "    var end = hop;",
            "    var count = 1;",
            "    while (end < t && count <= maxBounces) {",
            "        speed *= elasticity;",
            "        hop *= elasticity;",
            "        start = end;",
            "        end += hop;",
            "        count++;",
            "    }",
            "    if (count <= maxBounces) {",
            "        var d = t - start;",
            "        out = add(value, only(mul(dir, d * (speed - gravity * d / 2))));",
            "    }",
            "}",
            "out;"
        ]).join("\n");
    }

    function expressionFor(type, axis, names, inline) {
        return type === "overshoot" ? overshootExpression(axis, names, inline) : bounceExpression(axis, names, inline);
    }

    function isInline(src) {
        return !!src && src.indexOf("\n" + INLINE + "\n") > 0;
    }

    // The type and values of an expression that carries its own values, or null.
    function readInline(src) {
        if (!isInline(src)) return null;
        var type = typeOfExpression(src);
        if (!type) return null;
        var names = type === "overshoot"
            ? { amp: "amplitude", freq: "frequency", decay: "decay", floor: "floorOn" }
            : { elast: "elasticity", grav: "gravity", max: "maxBounces" };
        var vals = {};
        for (var key in names) {
            if (!names.hasOwnProperty(key)) continue;
            var m = new RegExp("var " + names[key] + " = (-?[0-9.]+);").exec(src);
            if (m && !isNaN(parseFloat(m[1]))) vals[key] = parseFloat(m[1]);
        }
        return { type: type, vals: vals };
    }

    // The same motion in plain JavaScript, for the preview. `v` is the speed at the keyframe.
    function motionAt(type, vals, v, t) {
        if (t <= 0) return 0;
        if (type === "overshoot") {
            var wave = Math.sin(vals.freq * t * 2 * Math.PI);
            if (vals.floor) wave = -Math.abs(wave);
            return v * (vals.amp / 1000) * wave / Math.exp(vals.decay * t);
        }
        var e = vals.elast / 100;
        var g = vals.grav * 100;
        var speed = Math.abs(v) * e;
        var dir = v < 0 ? 1 : -1;
        var start = 0;
        var hop = 2 * speed / g;
        var end = hop;
        var count = 1;
        while (end < t && count <= vals.max) {
            speed *= e;
            hop *= e;
            start = end;
            end += hop;
            count++;
        }
        if (count > vals.max) return 0;
        var d = t - start;
        return dir * d * (speed - g * d / 2);
    }

