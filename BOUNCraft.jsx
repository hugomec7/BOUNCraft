    var SETTINGS = NAME;

    function loadUserPresets(type) {
        try {
            if (!app.settings.haveSetting(SETTINGS, "presets." + type)) return [];
            var list = JSON.parse(app.settings.getSetting(SETTINGS, "presets." + type));
            return list instanceof Array ? list : [];
        } catch (e) {
            return [];
        }
    }

    function saveUserPresets(type, list) {
        try {
            app.settings.saveSetting(SETTINGS, "presets." + type, JSON.stringify(list));
            return true;
        } catch (e) {
            return false;
        }
    }

    function presetsOf(type) {
        var out = [];
        var b = TYPES[type].presets;
        for (var i = 0; i < b.length; i++) out.push({ name: b[i].name, v: b[i].v, builtIn: true });
        var u = loadUserPresets(type);
        for (var j = 0; j < u.length; j++) {
            if (u[j] && u[j].name && u[j].v) out.push({ name: String(u[j].name), v: u[j].v, builtIn: false });
        }
        return out;
    }

