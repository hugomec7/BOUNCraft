    // [{layer, prop}] for Bounce It.
    function targets(comp, which, axis) {
        var out = [];
        if (which === "selected") {
            var sel = comp.selectedProperties;
            for (var i = 0; i < sel.length; i++) {
                var p = sel[i];
                if (p.propertyType !== PropertyType.PROPERTY) continue;
                if (isOwnControl(p)) continue;
                out.push({ layer: layerOf(p), prop: p });
            }
            return out;
        }
        var layers = comp.selectedLayers;
        for (var j = 0; j < layers.length; j++) {
            var props = transformProperty(layers[j], which, axis);
            for (var k = 0; k < props.length; k++) {
                if (props[k]) out.push({ layer: layers[j], prop: props[k] });
            }
        }
        return out;
    }

    // [{layer, prop}] already bounced, for Bake and Remove: the selected properties that are,
    // or else every bounced property of the selected layers.
    function bouncedTargets(comp) {
        var out = [];
        var sel = comp.selectedProperties;
        for (var i = 0; i < sel.length; i++) {
            var p = sel[i];
            if (p.propertyType === PropertyType.PROPERTY && !isOwnControl(p) && bouncraftType(p)) {
                out.push({ layer: layerOf(p), prop: p });
            }
        }
        if (out.length) return out;
        var layers = comp.selectedLayers;
        for (var j = 0; j < layers.length; j++) {
            var props = bouncedProps(layers[j]);
            for (var k = 0; k < props.length; k++) out.push({ layer: layers[j], prop: props[k] });
        }
        return out;
    }

