        // ---- preview drawing
        var MOVE = 0.4; // seconds of the move into the keyframe
        var PREVIEW_MOVES = [
            { size: 500, label: "A 500 px move" },
            { size: 100, label: "Scale 0 to 100%" },
            { size: 180, label: "A half turn" },
            { size: 100, label: "A 100-unit move" }
        ];
        var AFTER = 2.0; // seconds shown after it
        preview.onDraw = function () {
            var g = this.graphics;
            var w = this.size.width;
            var h = this.size.height;
            if (!(w > 0 && h > 0)) return;
            g.newPath();
            g.rectPath(0, 0, w, h);
            g.fillPath(g.newBrush(g.BrushType.SOLID_COLOR, COLORS.bg));

            var type = state.type;
            var vals = state.vals[type];
            // A typical move of the chosen property in MOVE seconds. Bounce Back depends on the
            // size of the move (Overshoot doesn't), so the preview uses a real one.
            var which = prop.selection ? prop.selection.index : 1;
            var unit = PREVIEW_MOVES[which].size;
            var v = unit / MOVE;
            var N = 160;
            var pts = [];
            var peak = 0;
            for (var i = 0; i <= N; i++) {
                var t = -MOVE + (MOVE + AFTER) * i / N;
                var y = t < 0 ? unit * (t + MOVE) / MOVE : unit + motionAt(type, vals, v, t);
                pts.push([t, y]);
                if (t > 0 && Math.abs(y - unit) > Math.abs(peak)) peak = y - unit;
            }
            // Zoom in on the keyframe's value so a small bounce still shows; the move into it
            // runs off the bottom.
            var dev = Math.max(Math.abs(peak), unit * 0.002);
            var lo = unit - dev * 1.6;
            var hi = unit + dev * 1.6;
            var span = hi - lo;
            var top = 20;
            var bottom = h - 8;
            var left = 8;
            var right = w - 8;
            function X(t) { return left + (right - left) * (t + MOVE) / (MOVE + AFTER); }
            function Y(y) { return Math.max(top - 6, Math.min(bottom + 6, bottom - (bottom - top) * (y - lo) / span)); }

            // Keyframe time and the keyframe's value.
            g.newPath();
            g.moveTo(X(0), top - 4);
            g.lineTo(X(0), bottom + 4);
            g.strokePath(g.newPen(g.PenType.SOLID_COLOR, COLORS.grid, 1));
            g.newPath();
            g.moveTo(left, Y(unit));
            g.lineTo(right, Y(unit));
            g.strokePath(g.newPen(g.PenType.SOLID_COLOR, COLORS.target, 1));

            // The move (grey), then the bounce (orange).
            g.newPath();
            g.moveTo(X(pts[0][0]), Y(pts[0][1]));
            var j = 1;
            for (; j < pts.length && pts[j][0] <= 0; j++) g.lineTo(X(pts[j][0]), Y(pts[j][1]));
            g.strokePath(g.newPen(g.PenType.SOLID_COLOR, COLORS.move, 1.5));
            g.newPath();
            g.moveTo(X(0), Y(unit));
            for (; j < pts.length; j++) g.lineTo(X(pts[j][0]), Y(pts[j][1]));
            g.strokePath(g.newPen(g.PenType.SOLID_COLOR, COLORS.curve, 2));

            // Keyframe diamond.
            var kx = X(0);
            var ky = Y(unit);
            g.newPath();
            g.moveTo(kx, ky - 4);
            g.lineTo(kx + 4, ky);
            g.lineTo(kx, ky + 4);
            g.lineTo(kx - 4, ky);
            g.closePath();
            g.fillPath(g.newBrush(g.BrushType.SOLID_COLOR, COLORS.key));

            var pen = g.newPen(g.PenType.SOLID_COLOR, COLORS.text, 1);
            var small = ScriptUI.newFont("dialog", "REGULAR", 10);
            g.drawString(PREVIEW_MOVES[which].label + " in " + MOVE + " s", pen, left, 4, small);
            var pct = Math.round(Math.abs(peak) / unit * 1000) / 10;
            var txt = "peak " + pct + "%";
            g.drawString(txt, pen, right - g.measureString(txt, small).width, 4, small);
        };

        // ---- presets
        // The list shows the preset that matches the current values, or "Custom" first when
        // none does.
        var presets = [];
        var custom = false;
        var settingPreset = false;
        function matches(p) {
            var vals = state.vals[state.type];
            for (var key in vals) {
                if (!vals.hasOwnProperty(key)) continue;
                if (!p.v.hasOwnProperty(key) || Math.abs(Number(p.v[key]) - vals[key]) > 1e-6) return false;
            }
            return true;
        }
        function syncPreset() {
            settingPreset = true;
            presets = presetsOf(state.type);
            var pick = -1;
            for (var i = 0; i < presets.length && pick < 0; i++) if (matches(presets[i])) pick = i;
            custom = pick < 0;
            presetList.removeAll();
            if (custom) presetList.add("item", "Custom");
            for (var j = 0; j < presets.length; j++) {
                presetList.add("item", presets[j].builtIn ? presets[j].name : presets[j].name + " *");
            }
            presetList.selection = custom ? 0 : pick;
            delPreset.enabled = !custom && !presets[pick].builtIn;
            settingPreset = false;
        }
        function selectedPreset() {
            if (!presetList.selection) return null;
            var i = presetList.selection.index - (custom ? 1 : 0);
            return i >= 0 ? presets[i] || null : null;
        }
        function applyPreset(p) {
            var vals = copy(state.vals[state.type]);
            for (var key in p.v) if (p.v.hasOwnProperty(key) && vals.hasOwnProperty(key)) vals[key] = Number(p.v[key]);
            state.vals[state.type] = vals;
            showValues();
            refresh();
        }
        presetList.onChange = function () {
            if (settingPreset) return;
            var p = selectedPreset();
            if (!p) return;
            applyPreset(p);
            syncPreset();
        };
