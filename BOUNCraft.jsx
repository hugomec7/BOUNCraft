    function bounce(which, type, axis, vals) {
        var comp = activeComp();
        if (!comp) return;
        var list = targets(comp, which, axis);
        if (list.length === 0) {
            tell(which === "selected"
                ? "Select one or more properties (Position, Scale, an effect's property...)."
                : "Select one or more layers.");
            return;
        }
        var other = type === "overshoot" ? "bounce" : "overshoot";
        var done = 0;
        var viaPlugin = 0;
        var skipped = [];
        var touched = [];
        app.beginUndoGroup(NAME + ": " + TYPES[type].label);
        try {
            for (var i = 0; i < list.length; i++) {
                var layer = list[i].layer;
                var prop = list[i].prop;
                if (!prop.canSetExpression) {
                    skipped.push(layer.name + " > " + prop.name);
                    continue;
                }
                var fxName = setControls(layer, type, vals);
                if (fxName) viaPlugin++;
                // A one-dimensional property has no axis to choose.
                var a = typeof prop.value === "number" ? -1 : axis;
                prop.expression = expressionFor(type, a, fxName);
                prop.expressionEnabled = true;
                done++;
                addOnce(touched, layer);
            }
            for (var l = 0; l < touched.length; l++) removeIfUnused(touched[l], other);
        } catch (err) {
            tell("Something went wrong: " + err.message);
            return;
        } finally {
            app.endUndoGroup();
        }
        var report = TYPES[type].label + " on " + plural(done, "property", "properties")
            + (viaPlugin ? " (plug-in)." : ".");
        if (skipped.length) report += " Can't take an expression: " + skipped.join(", ");
        tell(report);
    }

    function sameValue(a, b, eps) {
        if (typeof a === "number") return Math.abs(a - b) <= eps;
        for (var i = 0; i < a.length; i++) if (Math.abs(a[i] - b[i]) > eps) return false;
        return true;
    }

    // Turns one property's bounce into keyframes: one per frame from its first keyframe until
    // the motion after the last one has settled (10 s at most), then drops the expression.
    function bakeProp(comp, prop) {
        var n = prop.numKeys;
        var fd = comp.frameDuration;
        if (n === 0) {
            prop.expression = "";
            return 0;
        }
        var first = prop.keyTime(1);
        var last = prop.keyTime(n);
        var stop = Math.min(comp.duration, last + 10);
        var times = [];
        var values = [];
        var still = 0;
        for (var t = first; t <= stop + fd / 2; t += fd) {
            var post = prop.valueAtTime(t, false);
            times.push(t);
            values.push(post);
            if (t > last) {
                still = sameValue(post, prop.valueAtTime(t, true), 0.01) ? still + 1 : 0;
                // Settled for a quarter of a second.
                if (still * fd >= 0.25) break;
            }
        }
        prop.expression = "";
        for (var i = 0; i < times.length; i++) prop.setValueAtTime(times[i], values[i]);
        return times.length;
    }

    function bake() {
        var comp = activeComp();
        if (!comp) return;
        var list = bouncedTargets(comp);
        if (!list.length) {
            tell("Select layers or properties with BOUNCraft on them.");
            return;
        }
        var keys = 0;
        var touched = [];
        app.beginUndoGroup(NAME + ": Bake");
        try {
            for (var i = 0; i < list.length; i++) {
                keys += bakeProp(comp, list[i].prop);
                addOnce(touched, list[i].layer);
            }
            for (var l = 0; l < touched.length; l++) {
                removeIfUnused(touched[l], "overshoot");
                removeIfUnused(touched[l], "bounce");
            }
        } catch (err) {
            tell("Something went wrong: " + err.message);
            return;
        } finally {
            app.endUndoGroup();
        }
        tell("Baked " + plural(list.length, "property", "properties") + " into " + plural(keys, "keyframe", "keyframes") + ".");
    }

    function removeBounce() {
        var comp = activeComp();
        if (!comp) return;
        var list = bouncedTargets(comp);
        if (!list.length) {
            tell("Select layers or properties with BOUNCraft on them.");
            return;
        }
        var touched = [];
        app.beginUndoGroup(NAME + ": Remove");
        try {
            for (var i = 0; i < list.length; i++) {
                list[i].prop.expression = "";
                addOnce(touched, list[i].layer);
            }
            for (var l = 0; l < touched.length; l++) {
                removeIfUnused(touched[l], "overshoot");
                removeIfUnused(touched[l], "bounce");
            }
        } catch (err) {
            tell("Something went wrong: " + err.message);
            return;
        } finally {
            app.endUndoGroup();
        }
        tell("Removed from " + plural(list.length, "property", "properties") + ".");
    }

