        // Seconds from the keyframe at this moment of the loop, or null when not playing.
        function playTime() {
            if (!playing()) return null;
            var phase = ((new Date().getTime() - anim.start) / 1000) % LOOP;
            return phase - HOLD - MOVE;
        }

