    var AXIS_LINES = [
        "function only(d) {",
        "    if (axis < 0 || typeof d == \"number\" || axis >= d.length) return d;",
        "    var m = mul(d, 0);",
        "    m[axis] = d[axis];",
        "    return m;",
        "}"
    ];

    // How an expression reads one value: from the effect plug-in when `fx` names it, otherwise
    // from the Slider / Checkbox Control named after the value.
    function ctl(type, key, fx) {
        if (fx) return "effect(" + JSON.stringify(fx) + ")(" + JSON.stringify(TYPES[type].plugin.params[key]) + ")";
        return "effect(" + JSON.stringify(controlName(type, key)) + ")(1)";
    }

    function controlName(type, key) {
        var T = TYPES[type];
        if (key === "on") return T.on;
        for (var i = 0; i < T.params.length; i++) if (T.params[i].key === key) return T.params[i].name;
        for (var j = 0; j < T.toggles.length; j++) if (T.toggles[j].key === key) return T.toggles[j].name;
        return key;
    }

    function overshootExpression(axis, fx) {
        return [
            TAG + "Overshoot",
            "var on = " + ctl("overshoot", "on", fx) + " == 1;",
            "var amp = " + ctl("overshoot", "amp", fx) + " / 1000;",
            "var freq = " + ctl("overshoot", "freq", fx) + ";",
            "var decay = " + ctl("overshoot", "decay", fx) + ";",
            "var floorOn = " + ctl("overshoot", "floor", fx) + " == 1;",
            "var axis = " + axis + ";"
        ].concat(AXIS_LINES, [
            "var out = value;",
            "var n = 0;",
            "if (on && numKeys > 0) {",
            "    n = nearestKey(time).index;",
            "    if (key(n).time > time) n--;",
            "}",
            "if (n > 0) {",
            "    var t = time - key(n).time;",
            "    var v = velocityAtTime(key(n).time - thisComp.frameDuration / 10);",
            "    var wave = Math.sin(freq * t * 2 * Math.PI);",
            "    if (floorOn) wave = -Math.abs(wave);",
            "    out = add(value, only(mul(v, amp * wave / Math.exp(decay * t))));",
            "}",
            "out;"
        ]).join("\n");
    }

    function bounceExpression(axis, fx) {
        return [
            TAG + "Bounce Back",
            "var on = " + ctl("bounce", "on", fx) + " == 1;",
            "var elasticity = " + ctl("bounce", "elast", fx) + " / 100;",
            "var gravity = " + ctl("bounce", "grav", fx) + " * 100;",
            "var maxBounces = " + ctl("bounce", "max", fx) + ";",
            "var axis = " + axis + ";"
        ].concat(AXIS_LINES, [
            "var out = value;",
            "var n = 0;",
            "if (on && numKeys > 0) {",
            "    n = nearestKey(time).index;",
            "    if (key(n).time > time) n--;",
            "}",
            "if (n > 0 && gravity > 0) {",
            "    var t = time - key(n).time;",
            "    var v = mul(velocityAtTime(key(n).time - 0.001), -elasticity);",
            "    var speed = length(v);",
            "    var dir;",
            "    if (typeof value == \"number\") dir = v < 0 ? -1 : 1;",
            "    else dir = speed > 0 ? normalize(v) : mul(v, 0);",
            "    var start = 0;",
            "    var hop = 2 * speed / gravity;",
            "    var end = hop;",
            "    var count = 1;",
            "    while (end < t && count <= maxBounces) {",
            "        speed *= elasticity;",
            "        hop *= elasticity;",
            "        start = end;",
            "        end += hop;",
            "        count++;",
            "    }",
            "    if (count <= maxBounces) {",
            "        var d = t - start;",
            "        out = add(value, only(mul(dir, d * (speed - gravity * d / 2))));",
            "    }",
            "}",
            "out;"
        ]).join("\n");
    }

    function expressionFor(type, axis, fx) {
        return type === "overshoot" ? overshootExpression(axis, fx) : bounceExpression(axis, fx);
    }

    // The same motion in plain JavaScript, for the preview. `v` is the speed at the keyframe.
    function motionAt(type, vals, v, t) {
        if (t <= 0) return 0;
        if (type === "overshoot") {
            var wave = Math.sin(vals.freq * t * 2 * Math.PI);
            if (vals.floor) wave = -Math.abs(wave);
            return v * (vals.amp / 1000) * wave / Math.exp(vals.decay * t);
        }
        var e = vals.elast / 100;
        var g = vals.grav * 100;
        var speed = Math.abs(v) * e;
        var dir = v < 0 ? 1 : -1;
        var start = 0;
        var hop = 2 * speed / g;
        var end = hop;
        var count = 1;
        while (end < t && count <= vals.max) {
            speed *= e;
            hop *= e;
            start = end;
            end += hop;
            count++;
        }
        if (count > vals.max) return 0;
        var d = t - start;
        return dir * d * (speed - g * d / 2);
    }

